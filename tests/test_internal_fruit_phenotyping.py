def test_analyze_image_creates_outputs():
    """
    Single image with QR code present.
    Results are saved in Image_Results folder.
    Note: session_report.txt is only generated by analyze_folder(), not save_all().
    """
    sample_data = "tests/sample_data/img_test_1.jpg"

    analyzer = FruitInternalAnalyzer(sample_data)
    analyzer.load_image(plot = False)
    analyzer.setup_measurements()
    analyzer.generate_fruit_mask(plot = False)
    analyzer.detect_fruits()
    analyzer.analyze_morphology(plot=False)
    analyzer.analyze_color(plot=False)
    analyzer.results.save_all(output_dir="tests/sample_data/Image_Results")

    results_dir = Path("tests/sample_data/Image_Results")

    # 1) Annotated image exists
    assert (results_dir / "img_test_1_annotated.jpg").exists()

    # 2) Morphology CSV exists and has at least one row
    morpho_results = results_dir / "img_test_1_morphology_results.csv"
    assert morpho_results.exists()
    morpho_df = pd.read_csv(morpho_results)
    assert len(morpho_df) > 0

    # 3) Color CSV exists and has at least one row
    color_results = results_dir / "img_test_1_color_results.csv"
    assert color_results.exists()
    color_df = pd.read_csv(color_results)
    assert len(color_df) > 0


