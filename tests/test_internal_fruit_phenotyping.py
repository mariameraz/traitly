def test_analyze_folder_creates_outputs():
    """
    Folder with 3 example images.
    2 images have QR codes, 1 image does not have a QR code.
    Results are saved by default inside sample_data/Results.
    img_test_4.jpg does not contain valid locules —
    the function should not stop but report the error.
    """
    sample_data = Path("tests/sample_data")

    analyzer = FruitInternalAnalyzer(sample_data)
    analyzer.analyze_folder(analyze_morphology=False)

    results_dir = sample_data / "Results"

    # 1) Output directory was created
    assert results_dir.is_dir()

    # 2) color_results.csv exists and has at least one row
    color_results = results_dir / "color_results.csv"
    assert color_results.exists()
    df = pd.read_csv(color_results)
    assert len(df) > 0

    # 3) session_report.txt exists (generated by analyze_folder)
    assert (results_dir / "session_report.txt").exists()


def test_analyze_folder_raises_if_not_directory():
    """Passing a single image path instead of a directory should raise ValueError."""
    example_img = "tests/sample_data/img_test_3.jpg"
    analyzer = FruitInternalAnalyzer(str(example_img))

    with pytest.raises(ValueError, match="not a single file"):
        analyzer.analyze_folder()


def test_analyze_folder_error_report_created_when_invalid_image():
    """
    When the folder contains an image that fails processing,
    error_report.txt should be created.
    """
